def balance_card(row):
    row.setdefault('upgradeDraw', -1)
    if row['hits'] > 1:
        row['upgradeDamage'] = min(row['upgradeDamage'], 1)
    row.update(CARD_OVERRIDES.get(row['id'], {}))

def balance_manor(row):
    if row['id'] in ('smith', 'armory', 'garden'):
        row['maxLevel'] = 2
    if row['id'] == 'vault':
        row['summary'] = '+5% legacy earnings per level, applied after trait bonuses.'

def class_rules(row):
    if row['id'] == 'knight':
        row['summary'] = 'Playing a Skill primes your next Attack for +2 damage on every hit. Attacking consumes the counter.'
    if row['id'] == 'mage':
        row['summary'] = 'Each Skill grants 1 Arcane Charge. Your next Attack consumes all charges to draw that many cards, once per turn. Charges dissipate at the end of your turn.'
