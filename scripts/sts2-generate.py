"""Generate/check stable saved identities only after the entire design validates."""
import argparse
import os
import pathlib
from preflight import validate
from design_schema import read_json
repo = pathlib.Path(__file__).resolve().parents[1]

def generated(sheets):
    cards = [r['id'] for r in sheets['cards']]
    powers = [r['id'] for r in sheets['power_effects']] + ['plated','reservoir','quiver','class']
    saved=read_json(repo/'scripts/saved-model-ids.json')
    for kind,ids in [('cards',cards),('powers',powers)]:
        missing=set(saved[kind])-set(ids)
        if missing:raise ValueError(f'{kind}: removed saved model IDs: '+', '.join(sorted(missing)))
    if len(powers)!=len(set(powers)):raise ValueError('power_effects.id: duplicate native alias')
    return {
        'Cards.cs': '// Generated by scripts/sts2-generate.py; stable saved-card identities.\nnamespace SpireLegacy;\n' + ''.join(f'public sealed class C_{key} : LegacyCard {{ public C_{key}() : base("{key}") {{ }} }}\n' for key in cards),
        'Powers.cs': '// Generated by scripts/sts2-generate.py; native aliases are selected in LegacyPowers.\nnamespace SpireLegacy;\n' + ''.join(f'public sealed class P_{key} : LegacyPower {{ }}\n' for key in powers)
    }

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    sheets=validate();outputs=generated(sheets);out=repo/'sts2/Generated'
    extras=set(p.name for p in out.glob('*.cs'))-outputs.keys()
    if extras:raise SystemExit('Generated: unexpected stale identities: '+', '.join(sorted(extras)))
    if args.check:
        # Git's Windows checkout may use CRLF; identities must match after newline normalization.
        stale=[name for name,text in outputs.items() if not (out/name).exists() or (out/name).read_text(encoding='utf-8')!=text]
        if stale:raise SystemExit('Generated models differ from sheets: '+', '.join(stale)+'; run scripts/sts2-generate.py')
    else:
        out.mkdir(parents=True,exist_ok=True)
        for name,text in outputs.items():
            temporary=out/(name+'.tmp');temporary.write_bytes(text.encode('utf-8'));os.replace(temporary,out/name)
    print(f'{"Checked" if args.check else "Generated"} {len(sheets["cards"])} cards and {len(sheets["power_effects"])+4} power identities; stable regular/beta pools.')

if __name__=='__main__':
    try:main()
    except ValueError as error:raise SystemExit(str(error))
